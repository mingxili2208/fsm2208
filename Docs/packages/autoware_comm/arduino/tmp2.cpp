/***
 * @brief Function for verifying; 1 as true, 0 as false
 * @param data
 * @return status of the verification
 */
u8 verifyChecksum(u8* data) {
  u8 checksum = 0;
  for (int i = 2; i <= 6; i++) {
    checksum ^= data[i];
  }
  if (checksum == data[7])
	return 1;
  else return 0;
}
